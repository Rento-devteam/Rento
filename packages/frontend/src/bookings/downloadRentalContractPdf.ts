/**
 * Векторный PDF формата A4 (pdfmake): текст в миллиметрах, переносы по ширине страницы,
 * без растрового «скриншота» — одинаково на телефоне и на десктопе.
 */
function vfsFromVfsFontsModule(mod: unknown): Record<string, string> {
  if (mod && typeof mod === "object" && "default" in mod) {
    const d = (mod as { default?: unknown }).default;
    if (d && typeof d === "object") return d as Record<string, string>;
  }
  return mod as Record<string, string>;
}

export async function downloadRentalContractPdf(
  props: RentalContractBodyProps,
  filename: string,
): Promise<void> {
  const pdfMake = await import("pdfmake/build/pdfmake");
  const vfsModule: unknown = await import("pdfmake/build/vfs_fonts");
  const vfs = vfsFromVfsFontsModule(vfsModule);

  pdfMake.addVirtualFileSystem(vfs);
  pdfMake.setFonts({
    Roboto: {
      normal: "Roboto-Regular.ttf",
      bold: "Roboto-Medium.ttf",
      italics: "Roboto-Italic.ttf",
      bolditalics: "Roboto-MediumItalic.ttf",
    },
  });

  const docDefinition = buildDocumentDefinition(props);
  pdfMake.createPdf(docDefinition).download(filename);
}
